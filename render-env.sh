#!/usr/bin/env bash
# Render the node-local .env.inkling (read by docker compose) from cluster.env.
# Usage: render-env.sh <head|worker>   — writes $KIT/.env.inkling
set -euo pipefail

ROLE="${1:?usage: render-env.sh <head|worker>}"
KIT="$(cd "$(dirname "$0")" && pwd)"
# shellcheck disable=SC1091
source "$KIT/cluster.env"

case "$ROLE" in
  head)   NODE_RANK=0; HEADLESS=;  VLLM_HOST_IP="$HEAD_R1" ;;
  worker) NODE_RANK=1; HEADLESS=1; VLLM_HOST_IP="$WORKER_R1" ;;
  *) echo "unknown role $ROLE" >&2; exit 1 ;;
esac

# NOTE: UNQUOTED heredoc — a leading '#' does NOT stop expansion. A variable reference left on
# a "commented" line still expands, and under set -u an unset one aborts this script (the trap
# that took prod down 2026-07-26). Keep disabled lines name-only, with no dollar sign at all.
cat > "$KIT/.env.inkling" <<EOF
# GENERATED by render-env.sh ($ROLE) — edit cluster.env, not this file.
INKLING_VLLM_IMAGE=$INKLING_VLLM_IMAGE
INKLING_MODEL=$INKLING_MODEL
SERVED_MODEL_NAME=$SERVED_MODEL_NAME
HF_CACHE=$HF_CACHE
HF_HUB_OFFLINE=1
TRANSFORMERS_OFFLINE=1
VLLM_HOST=$VLLM_HOST
API_PORT=$API_PORT
MAX_MODEL_LEN=$MAX_MODEL_LEN
MAX_NUM_SEQS=$MAX_NUM_SEQS
MAX_NUM_BATCHED_TOKENS=$MAX_NUM_BATCHED_TOKENS
GPU_MEMORY_UTILIZATION=$GPU_MEMORY_UTILIZATION
KV_CACHE_MEMORY_BYTES=${KV_CACHE_MEMORY_BYTES:-}
MOE_BACKEND=${MOE_BACKEND:-}
MTP_NUM_TOKENS=${MTP_NUM_TOKENS:-}
REASONING_EFFORT=${REASONING_EFFORT:-}
DISABLE_CUSTOM_ALL_REDUCE=${DISABLE_CUSTOM_ALL_REDUCE:-}
ENFORCE_EAGER=${ENFORCE_EAGER:-}
SHUTDOWN_TIMEOUT=${SHUTDOWN_TIMEOUT:-0}
MASTER_ADDR=$MASTER_ADDR
MASTER_PORT=$MASTER_PORT
NODE_RANK=$NODE_RANK
HEADLESS=$HEADLESS
VLLM_HOST_IP=$VLLM_HOST_IP
NCCL_SOCKET_IFNAME=$NCCL_SOCKET_IFNAME
NCCL_IB_HCA=$NCCL_IB_HCA
NCCL_IB_GID_INDEX=$NCCL_IB_GID_INDEX
NCCL_CROSS_NIC=$NCCL_CROSS_NIC
NCCL_IB_MERGE_NICS=$NCCL_IB_MERGE_NICS
NCCL_NET=$NCCL_NET
NCCL_IB_DISABLE=$NCCL_IB_DISABLE
NCCL_IB_ADDR_FAMILY=$NCCL_IB_ADDR_FAMILY
NCCL_IB_ROCE_VERSION_NUM=$NCCL_IB_ROCE_VERSION_NUM
NCCL_IB_ADDR_RANGE=$NCCL_IB_ADDR_RANGE
TP_SOCKET_IFNAME=$TP_SOCKET_IFNAME
GLOO_SOCKET_IFNAME=${GLOO_SOCKET_IFNAME:-$NCCL_SOCKET_IFNAME}
NCCL_DEBUG=${NCCL_DEBUG:-WARN}
NCCL_DEBUG_SUBSYS=${NCCL_DEBUG_SUBSYS:-}
VLLM_EXECUTE_MODEL_TIMEOUT_SECONDS=$VLLM_EXECUTE_MODEL_TIMEOUT_SECONDS
TRITON_PTXAS_PATH=$TRITON_PTXAS_PATH
VLLM_LOGGING_LEVEL=${VLLM_LOGGING_LEVEL:-INFO}
FA4_BUNDLE_DIR=${FA4_BUNDLE_DIR:-}
SHIM_PATH=${SHIM_PATH:-$KIT_DIR/image/fa4_sm120_shim.py}
EOF
chmod 600 "$KIT/.env.inkling"
echo "rendered $KIT/.env.inkling ($ROLE)"
